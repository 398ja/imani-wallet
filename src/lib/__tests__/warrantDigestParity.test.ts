/**
 * The TypeScript digest must be byte-identical to the Java one.
 *
 * This is the test that fails if the scheme is quietly broken. The merchant's
 * device signs in TypeScript; `IssuanceWarrant.java` verifies. A preimage that
 * differs by one byte between them is not a subtle bug — it is a system where
 * every genuine warrant is refused, every merchant sees "authorisation failed"
 * on a coupon they just authorised, and the logs say only that a signature did
 * not verify.
 *
 * The vectors below were PRODUCED BY the Java implementation, not written by
 * hand to match the TypeScript. They were generated by calling
 * `IssuanceWarrant.saleDigest` directly:
 *
 *   IssuanceWarrant.saleDigest(stall, 2500, 2, "EUR", "b7f3a1c2d4e5f607")
 *
 * so agreement here means the two implementations agree, rather than that one
 * of them agrees with itself.
 *
 * **If this file fails, do not "fix" it by regenerating the vectors.** A
 * mismatch means one side changed its preimage, and the question is which side
 * and whether any coupons were issued under the old one.
 */
import { describe, it, expect } from 'vitest'
import { bytesToHex } from '@noble/hashes/utils'

import { warrantSaleDigest } from '../issuanceWarrant'

const STALL = 'b1787b2b98a5244a70d934b393e0179e7ebba0c72579b4a0b238eda3911caa02'

/** [saleTotal, faceDecimals, unit, nonce, expectedDigestHex] — Java's output. */
const JAVA_VECTORS: Array<[number, number, string, string, string]> = [
  // An ordinary counter sale, EUR 25.00.
  [2500, 2, 'EUR', 'b7f3a1c2d4e5f607',
    '033e27090dc97592cea2cda7895b45ce8713063514c5ee12a64de95afb06fd26'],

  // Zero, and a zero-decimal currency. Both are edge cases in the preimage:
  // `0` must serialise as "0" on both sides rather than "" or "0.0".
  [0, 0, 'XAF', 'aaaa',
    '22cd19453cb22fb53c1067d1c212674a1df359b51b1edcbb0a34663352e360ce'],

  // A large amount, and a nonce containing non-hex characters. Java's
  // Long.toString and JS's String() must agree at this magnitude, and the
  // nonce must not be assumed hex.
  [5000000, 2, 'EUR', 'nonce-with-dashes',
    '9e92f1b72bfdfe03a71e3223b71747a59594a9964ca5833d4747814eac091071'],

  // THE COLLISION PAIR. Concatenated without a separator both of these are
  // "...2500collide". They must produce different digests on BOTH sides, or a
  // warrant for EUR 0.25 verifies against a coupon for EUR 25.00.
  [25, 0, 'EUR', 'collide',
    '7271e7e949f382d53602073fddff215792852b42eb5c083e208954fb5e9ca21a'],
  [2, 50, 'EUR', 'collide',
    'f4990ae013ad3790f154080cb27744a377f98cfbd40a425fa825979e8484c050'],

  // Eight decimals, as BTC would use. Guards against either side formatting
  // decimals differently at the extreme.
  [1, 8, 'BTC', 'zzz',
    '2793839c5bd4e55622c6764b6f815ffa454848fd62eeb6e4236347c74f6b9909'],
]

describe('digest parity with IssuanceWarrant.java', () => {
  it.each(JAVA_VECTORS)(
    'matches Java for total=%s decimals=%s unit=%s nonce=%s',
    (total, decimals, unit, nonce, expected) => {
      expect(bytesToHex(warrantSaleDigest(STALL, total, decimals, unit, nonce))).toBe(expected)
    },
  )

  it('the collision pair differs on this side too', () => {
    // Belt and braces. The vectors above already pin both values, but this
    // states the PROPERTY rather than the constants, so it keeps meaning
    // something if the vectors are ever regenerated.
    const a = bytesToHex(warrantSaleDigest(STALL, 25, 0, 'EUR', 'collide'))
    const b = bytesToHex(warrantSaleDigest(STALL, 2, 50, 'EUR', 'collide'))
    expect(a).not.toBe(b)
  })
})
